const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
if(require('node:fs').existsSync(path.join(root,'src/assets.json'))) throw new Error('Source has already been extracted. Edit src/ and run npm run build.');
const original = path.join(root, 'GeoGlyph_Locate_2026.html');
const source = fs.readFileSync(original, 'utf8');
fs.mkdirSync(path.join(root, 'tests/fixtures'), { recursive: true });
const baseline = path.join(root, 'tests/fixtures/baseline.html');
if (!fs.existsSync(baseline)) fs.writeFileSync(baseline, source);
const assets = [];
let ordinal = 0;
const template = source.replace(/<(script|style)\b([^>]*)>([\s\S]*?)<\/\1\s*>/gi, (match, type, attrs, content) => {
  const n = ordinal++;
  const id = attrs.match(/\bid="([^"]+)"/)?.[1];
  const url = attrs.match(/\bsrc="([^"]+)"/)?.[1];
  const name = id || ({ 0: 'opentype', 1: 'qrious', 2: 'qrcode', 3: 'jszip', 4: 'base', 7: 'core' })[n] || `asset-${n}`;
  const vendor = [0, 1, 2, 3, 5, 34].includes(n);
  const relative = `src/${vendor ? 'vendor' : type === 'style' ? 'styles' : 'scripts'}/${name}.${type === 'style' ? 'css' : 'js'}`;
  const destination = path.join(root, relative);
  fs.mkdirSync(path.dirname(destination), { recursive: true });
  if (!url) fs.writeFileSync(destination, content);
  assets.push({ key: name, type, attrs: type === 'style' && id === 'geoglyph-map-engine-inline' ? ' id="geoglyph-map-engine-style"' : attrs.replace(/\s*src="[^"]*"/, ''), path: relative, ...(url ? { originalUrl: url } : {}) });
  return `<!-- GE0GLYPH_ASSET:${name} -->`;
});
fs.writeFileSync(path.join(root, 'src/template.html'), template);
fs.writeFileSync(path.join(root, 'src/assets.json'), JSON.stringify(assets, null, 2) + '\n');
fs.writeFileSync(path.join(root, 'tests/fixtures/baseline.sha256'), crypto.createHash('sha256').update(source).digest('hex') + '\n');
console.log(`Extracted ${assets.length} ordered assets. Baseline preserved.`);
